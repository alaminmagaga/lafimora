// Netlify build: copies the static site into dist/ without the local key file,
// and writes an ai-config.js that sends chat requests to the /api/ai function.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'dist');

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

for (const f of fs.readdirSync(root)) {
  if (f.endsWith('.html')) fs.copyFileSync(path.join(root, f), path.join(out, f));
}
fs.cpSync(path.join(root, 'assets'), path.join(out, 'assets'), {
  recursive: true,
  filter: (src) => path.basename(src) !== 'ai-config.js' // never publish local API keys
});

fs.writeFileSync(path.join(out, 'assets/js/ai-config.js'),
  "/* Generated by scripts/build.mjs: keys live in Netlify environment variables, used by netlify/functions/ai.mjs */\n" +
  "window.LAFIMORA_AI = { proxyUrl: '/api/ai' };\n");

const leaked = fs.readdirSync(out, { recursive: true }).filter((f) => /\.(js|html|json)$/.test(f))
  .filter((f) => /\b(gsk_|sk-)[A-Za-z0-9_-]{20,}/.test(fs.readFileSync(path.join(out, f), 'utf8')));
if (leaked.length) { console.error('API key found in build output:', leaked); process.exit(1); }

console.log(`Built ${fs.readdirSync(out, { recursive: true }).length} files into dist/`);
